    v_col     VARCHAR2(40);
BEGIN
    FOR i IN 1 .. v_cols.COUNT LOOP
        v_tab := SUBSTR(v_cols(i), 1, INSTR(v_cols(i), '.') - 1);
        v_col := SUBSTR(v_cols(i), INSTR(v_cols(i), '.') + 1);
        SELECT COUNT(*) INTO v_count FROM user_tab_columns
         WHERE table_name = v_tab AND column_name = v_col;
        IF v_count = 0 THEN
            DBMS_OUTPUT.PUT_LINE('MISSING COLUMN: ' || v_cols(i));
            v_missing := v_missing + 1;
        END IF;
    END LOOP;

    FOR i IN 1 .. v_seqs.COUNT LOOP
        SELECT COUNT(*) INTO v_count FROM user_sequences WHERE sequence_name = v_seqs(i);
        IF v_count = 0 THEN
            DBMS_OUTPUT.PUT_LINE('MISSING SEQUENCE: ' || v_seqs(i));
            v_missing := v_missing + 1;
        END IF;
    END LOOP;

    FOR o IN (SELECT object_type, object_name FROM user_objects
               WHERE status <> 'VALID'
                 AND (object_name LIKE 'SES%' OR object_name LIKE 'APP%')) LOOP
        DBMS_OUTPUT.PUT_LINE('INVALID ' || o.object_type || ': ' || o.object_name);
        v_missing := v_missing + 1;
    END LOOP;

    -- The two badge chains must be in the 7-step shape after 60.
    FOR c IN (SELECT chain_key FROM ses_approval_chain
               WHERE chain_key IN ('BADGE_DEFAULT', 'BADGE_PAYMENT')) LOOP
        SELECT COUNT(*) INTO v_count FROM ses_approval_step s
          JOIN ses_approval_chain ch ON ch.chain_id = s.chain_id
         WHERE ch.chain_key = c.chain_key;
        IF v_count <> 7 THEN
            DBMS_OUTPUT.PUT_LINE('CHAIN ' || c.chain_key || ' has ' || v_count || ' steps, expected 7');
            v_missing := v_missing + 1;
        END IF;
    END LOOP;

    IF v_missing > 0 THEN
        RAISE_APPLICATION_ERROR(-20099, 'Verifikasi 261019 gagal: ' || v_missing || ' masalah, lihat daftar di atas.');
    END IF;
    DBMS_OUTPUT.PUT_LINE('Verifikasi 261019 OK: ' || v_cols.COUNT || ' kolom, '
        || v_seqs.COUNT || ' sequence, semua objek SES/APP VALID, chain badge 7 tahap.');
END;
